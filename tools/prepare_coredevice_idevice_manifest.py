#!/usr/bin/env python3
"""Reduce the vendored manifest to the audited native backend dependency closure.
Unused feature names remain declared for rustc cfg checking, but are not supported.
No source/dependency download; preserves original manifest beside generated one.
"""
import json
import pathlib
import tomllib
root = pathlib.Path(__file__).resolve().parent.parent
p = root / 'coredevice/rust/vendor/idevice/Cargo.toml'
data = tomllib.loads(p.with_suffix('.toml.upstream').read_text())
selected = {'ring', 'remote_pairing', 'tunnel_tcp_stack', 'display_stream', 'mobile_image_mounter'}
closure = set()
features = data['features']
def visit(name):
    if name in closure: return
    closure.add(name)
    for ref in features[name]:
        if ref in features: visit(ref)
for name in selected: visit(name)
refs = {r for name in closure for r in features[name]}
used_deps = {r[4:] for r in refs if r.startswith('dep:')} | {r.split('/')[0] for r in refs if '/' in r}
def value(v):
    if isinstance(v, dict): return '{' + ', '.join(f'{k} = {value(x)}' for k,x in v.items()) + '}'
    return json.dumps(v)
lines = ['# Generated by tools/prepare_coredevice_idevice_manifest.py. Native CoreDevice profile only.', '[package]']
lines += [f'{k} = {value(v)}' for k,v in data['package'].items()]
lines += ['', '[dependencies]']
lines += [f'{k} = {value(v)}' for k,v in data['dependencies'].items() if not isinstance(v, dict) or not v.get('optional', False) or k in used_deps]
for target in ['cfg(not(windows))', 'cfg(not(target_arch = "wasm32"))']:
    lines += ['', f"[target.'{target}'.dependencies]"]
    lines += [f'{k} = {value(v)}' for k,v in data['target'][target]['dependencies'].items()]
lines += ['', '[dev-dependencies]', 'tokio = {version="1", features=["io-util", "rt", "sync", "time", "macros"]}', '', '[features]']
for k,v in features.items(): lines += [f'{k} = {value(v if k in closure else [])}']
p.write_text('\n'.join(lines) + '\n')
